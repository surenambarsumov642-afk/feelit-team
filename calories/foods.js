const norm = s => String(s).toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я0-9%,. ]/g, " ").replace(/\s+/g, " ").trim();

export const FOODS = RAW.map(([name, kcal, p, f, c, pc = 0, alias = ""]) => ({
  name, kcal, p, f, c, pc, key: norm(name + " " + alias),
}));

/** Поиск по началу слов: «грудка кур» найдёт «куриная грудка отварная». */
export function searchFoods(q, limit = 8) {
  const words = norm(q).split(" ").filter(w => w.length > 0 && !/^\d/.test(w) && !["г", "гр", "грамм"].includes(w));
  if (!words.length) return [];
  const res = [];
  for (const f of FOODS) {
    const tokens = f.key.split(" ");
    if (!words.every(w => tokens.some(t => t.startsWith(w)))) continue;
    const score = (norm(f.name).startsWith(words.join(" ")) ? 0 : 1) + f.name.length / 100;
    res.push([score, f]);
  }
  return res.sort((a, b) => a[0] - b[0]).slice(0, limit).map(x => x[1]);
}

/** Граммы из текста: «гречка 150 г» → 150. */
export function gramsFromText(q) {
  const m = String(q).match(/(\d+(?:[.,]\d+)?)\s*(?:грамм|гр|г|мл|ml|g)?(?=\s|$)/i);
  return m ? parseFloat(m[1].replace(",", ".")) : 0;
}
